#!/usr/bin/env python3
"""Typeset the exercise kit's EXERCISES.md as parts-2-3.pdf.

The Markdown in grading/A2/exercise_kit/src/EXERCISES.md is the source of truth
(it ships inside the kit); this script regenerates main.tex from it with the
course handout style and the same converter as hw2.tex, so the PDF cannot
drift from the kit. Run from this directory:

    python3 build.py && latexmk -pdf -interaction=nonstopmode main.tex && latexmk -c

The header dates below are the only hand-maintained text; keep them equal to
the handout's current revision.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(HERE.parent / "tools"))
import md2tex  # noqa: E402  (assignments/A2/tools/md2tex.py)

SRC = REPO / "grading" / "A2" / "exercise_kit" / "src" / "EXERCISES.md"
DST = HERE / "main.tex"
KIT_URL = "https://github.com/matthewdgreen/practicalcrypto2026/blob/main/assignments/A2/exercise-kit.zip"

DATE = "November 9, 2026"                    # handout Revision 3
DUE = "Due: 11:59 pm, November 20"
TITLE = "Assignment 2, Parts 2 and 3: break it"

PREAMBLE = r"""\documentclass[11pt]{article}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{graphicx,url,xspace,amsmath,amsfonts,booktabs,enumitem,array}
\usepackage[hidelinks]{hyperref}
\setlength{\oddsidemargin}{.25in}
\setlength{\evensidemargin}{.25in}
\setlength{\textwidth}{6in}
\setlength{\topmargin}{-0.4in}
\setlength{\textheight}{8.5in}
\setlist{nosep}

\def\subjnum{601.445/601.645}
\def\subjname{Practical Cryptographic Systems}

\newcommand{\handout}[5]{
  \renewcommand{\thepage}{#1-\arabic{page}}
  \noindent
  \begin{center}
    \framebox{
      \vbox{
        \hbox to 5.78in { {\bf \subjnum: \subjname} \hfill #2 }
        \vspace{4mm}
        \hbox to 5.78in { {\Large \hfill #5  \hfill} }
        \vspace{2mm}
        \hbox to 5.78in { {\it #3 \hfill #4} }
        }
      }
  \end{center}
  \vspace*{4mm}
  }

\newcommand{\code}[1]{\texttt{#1}}
\newcommand{\file}[1]{\texttt{#1}}

\emergencystretch=1.5em

% GENERATED by build.py from grading/A2/exercise_kit/src/EXERCISES.md.
% Do not edit by hand; edit the Markdown and rebuild.
\hypersetup{
  pdftitle={Assignment 2, Parts 2 and 3: break it},
  pdfauthor={Matthew Green},
  pdfsubject={Practical Cryptographic Systems: exercise kit instructions}
}

\begin{document}
"""


def wrap_commands(tex):
    """Break long runner commands in verbatim blocks before --part (a shell continuation)."""
    out = []
    for line in tex.split("\n"):
        if len(line) > 78 and line.startswith("python run_exercises.py") and " --part " in line:
            head, tail = line.split(" --part ", 1)
            out += [head + " \\", "    --part " + tail]
        else:
            out.append(line)
    return "\n".join(out)


def main():
    body = wrap_commands(md2tex.convert(SRC.read_text(encoding="utf-8")))
    header = (r"\handout{A2 Exercises}{%s}{Instructor: Matthew Green}{%s}{%s}" % (DATE, DUE, TITLE)
              + "\n\n"
              + r"\noindent\emph{This is the kit's \file{EXERCISES.md}, typeset. The kit itself, "
              + r"with \file{API.md}, \file{REVIEW-LAB.md}, and the \file{AGENTS.md} addendum, is at} "
              + r"\url{" + KIT_URL + "}" + "\n\n")
    DST.write_text(PREAMBLE + header + body + "\n\\end{document}\n", encoding="utf-8")
    print(f"wrote {DST} ({len(body.splitlines())} body lines) from {SRC.relative_to(REPO)}")


if __name__ == "__main__":
    main()
